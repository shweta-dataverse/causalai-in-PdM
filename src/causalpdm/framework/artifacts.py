"""Stage artifact cache shared by the framework notebooks.

Causal discovery is the expensive stage (minutes, not seconds). Notebooks
therefore persist each stage's output and reload it instead of recomputing, so
the pipeline can be inspected, re-run and demonstrated stage by stage without
paying for PCMCI+ every time.

Artifacts are pickles keyed by stage name. They are build outputs, not source:
the directory is gitignored and every artifact can be regenerated by rerunning
the notebooks or `scripts/run_pipeline.py`.
"""

from __future__ import annotations

import pickle
from pathlib import Path
from typing import Any, Callable

from ..config import REPO_ROOT

ARTIFACT_DIR = REPO_ROOT / "artifacts" / "framework"


def path_for(stage: str) -> Path:
    return ARTIFACT_DIR / f"{stage}.pkl"


def save(stage: str, obj: Any) -> Path:
    """Persist a stage output."""
    ARTIFACT_DIR.mkdir(parents=True, exist_ok=True)
    target = path_for(stage)
    with target.open("wb") as fh:
        pickle.dump(obj, fh, protocol=pickle.HIGHEST_PROTOCOL)
    return target


def load(stage: str) -> Any:
    """Load a stage output, raising a clear error if the stage has not run."""
    target = path_for(stage)
    if not target.exists():
        raise FileNotFoundError(
            f"Artifact '{stage}' not found at {target}. "
            f"Run the notebook that produces it, or scripts/run_pipeline.py."
        )
    with target.open("rb") as fh:
        return pickle.load(fh)


def exists(stage: str) -> bool:
    return path_for(stage).exists()


def cached(stage: str, compute: Callable[[], Any], force: bool = False) -> Any:
    """Return a cached stage output, computing and storing it on a miss."""
    if not force and exists(stage):
        return load(stage)
    result = compute()
    save(stage, result)
    return result


def clear(stage: str | None = None) -> None:
    """Delete one artifact, or all of them when `stage` is None."""
    if stage is not None:
        path_for(stage).unlink(missing_ok=True)
        return
    if ARTIFACT_DIR.exists():
        for file in ARTIFACT_DIR.glob("*.pkl"):
            file.unlink()
